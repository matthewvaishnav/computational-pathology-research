"""Pre-outcome semantic binding for PA-NF v5 RT1 SCORPION manifests.

The historical evidence package binds raw CSV bytes. RT1 additionally requires
scientific identity of the split: exact row-key agreement with the frozen feature
archive and the deterministic slide-level split generated by the original
SCORPION manifest builder (5 folds, seed 2026, test=k, val=k+1).

This module does not inspect or compute RT1 model outcomes.
"""
from __future__ import annotations

from pathlib import Path
from typing import Any

from experiments.scorpion.run_pathoalign_crossfold import align_fold
from scripts.scorpion.build_scorpion_manifest import assign_slide_folds

FOLD_SEED = 2026
N_FOLDS = 5


def expected_split_for_slide(slide_id: str, slide_folds: dict[str, int], test_fold: int) -> str:
    assigned = int(slide_folds[slide_id])
    val_fold = (int(test_fold) + 1) % N_FOLDS
    if assigned == int(test_fold):
        return "test"
    if assigned == val_fold:
        return "val"
    return "train"


def validate_manifest_semantics(
    base_features,
    base_frame,
    manifest_path: Path,
    fold: int,
) -> tuple[Any, Any, dict[str, Any]]:
    """Validate one runtime manifest without relying on CSV byte serialization."""
    features, frame = align_fold(base_features, base_frame, manifest_path)

    slide_ids = sorted(set(base_frame["slide_id"].astype(str)))
    if len(slide_ids) != 48:
        raise ValueError(f"expected 48 source slides in frozen feature archive, found {len(slide_ids)}")
    slide_folds = assign_slide_folds(slide_ids, n_folds=N_FOLDS, seed=FOLD_SEED)

    observed_by_slide: dict[str, set[str]] = {}
    for slide_id, split in zip(frame["slide_id"].astype(str), frame["split"].astype(str)):
        observed_by_slide.setdefault(slide_id, set()).add(split)

    if set(observed_by_slide) != set(slide_ids):
        missing = sorted(set(slide_ids) - set(observed_by_slide))
        extra = sorted(set(observed_by_slide) - set(slide_ids))
        raise ValueError(f"runtime manifest slide set differs from frozen features: missing={missing}, extra={extra}")

    mismatches = []
    for slide_id in slide_ids:
        observed = observed_by_slide[slide_id]
        expected = expected_split_for_slide(slide_id, slide_folds, int(fold))
        if observed != {expected}:
            mismatches.append((slide_id, expected, sorted(observed)))
    if mismatches:
        raise ValueError(
            f"fold {fold} differs from deterministic seed-{FOLD_SEED} slide split; first mismatches={mismatches[:10]}"
        )

    counts = {
        role: len({
            str(v)
            for v in frame.loc[frame["split"].astype(str) == role, "slide_id"].astype(str)
        })
        for role in ("train", "val", "test")
    }
    expected_counts = {"train": 28, "val": 10 if ((fold + 1) % 5) < 3 else 9, "test": 10 if fold < 3 else 9}
    # With 48 slides distributed round-robin over five folds, fold sizes are 10,10,10,9,9.
    fold_sizes = {k: sum(1 for value in slide_folds.values() if value == k) for k in range(N_FOLDS)}
    expected_counts = {
        "test": fold_sizes[int(fold)],
        "val": fold_sizes[(int(fold) + 1) % N_FOLDS],
        "train": 48 - fold_sizes[int(fold)] - fold_sizes[(int(fold) + 1) % N_FOLDS],
    }
    if counts != expected_counts:
        raise ValueError(f"fold {fold} slide counts differ: observed={counts}, expected={expected_counts}")

    return features, frame, {
        "fold": int(fold),
        "fold_seed": FOLD_SEED,
        "split_rule": "test=k; val=(k+1)%5; remaining=train",
        "slide_counts": counts,
        "row_count": int(len(frame)),
        "semantic_match": True,
    }
